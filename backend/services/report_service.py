"""Report service — orchestrates report creation and retrieval.

Storage is intentionally isolated behind a repository interface so it can be
swapped from in-memory to Supabase without changing the service contract.
All business logic stays here; route handlers remain thin (Part A §6).

Persistence strategy:
  1. Always build the ReportOut object and write it to _STORE (in-memory).
  2. If Supabase is fully configured (URL + SERVICE_KEY), also persist to the
     public.reports table via report_repo, using the authenticated user_id.
  3. On any Supabase error, the in-memory entry is already present so the
     response is unaffected.

Read strategy:
  1. Try Supabase first (get_report / list_reports).
  2. Fall back to _STORE if Supabase is unconfigured or the row is not found.
  This means data written to Supabase is visible even after a process restart,
  while the app degrades gracefully to in-memory when Supabase is unavailable.

T3-3 security notes:
  - create_report() accepts an optional user_id from the authenticated JWT sub.
  - DEMO_USER_ID is used as fallback only when user_id is not provided (local dev
    without auth enabled, or in-memory-only mode).
  - _supabase_enabled() no longer requires DEMO_USER_ID; URL + SERVICE_KEY suffice.
  - get_report_with_owner() returns (ReportOut, owner_user_id) for IDOR checks.

T3-3 AI pipeline notes:
  - create_report_from_image() is the new async function that wires together:
      image validation (T2-2) → AI pipeline (T2-11) → storage upload → DB insert
  - The existing sync create_report() is preserved unchanged for backward
    compatibility with existing tests and the non-image code path.
  - Signed URLs (15-min expiry) are generated by storage_service and attached
    to the ReportOut before returning (Part A §20).
"""
from __future__ import annotations

import logging
import uuid
from datetime import datetime, timezone
from typing import Optional

from config import settings
from schemas.report import (
    AuthorityOut,
    IssueCategory,
    ReportCreate,
    ReportOut,
    ReportStatus,
    CATEGORY_LABELS,
)
from services.authority_service import get_authority_by_id, route_to_authority

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# In-memory demo repository — kept intact as fallback (Part A §6, T3-3)
# ---------------------------------------------------------------------------

_STORE: dict[str, ReportOut] = {}

# Maps report_id → owner user_id for IDOR checks on the in-memory fallback.
_OWNER_STORE: dict[str, str] = {}


