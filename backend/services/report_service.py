def _supabase_enabled() -> bool:
    """True when Supabase URL and service key are configured.

    DEMO_USER_ID is no longer required here — T3-3 supplies the authenticated
    user_id at call time.  DEMO_USER_ID is only used as a fallback inside
    create_report() when no authenticated user_id is provided (local dev).
    """
    return bool(
        settings.SUPABASE_URL
        and settings.SUPABASE_SERVICE_KEY
    )


def _authority_dict_to_out(a: Optional[dict]) -> Optional[AuthorityOut]:
    if a is None:
        return None
    return AuthorityOut(
        id=a["id"],
        name=a["name"],
        short_name=a["short_name"],
        contact_email=a["contact_email"],
        phone=a["phone"],
    )


def _row_to_report_out(row: dict) -> Optional[ReportOut]:
    """Convert a public.reports DB row dict into a ReportOut.

    Field mapping (DB → API):
      id                   → report_id
      ai_category          → category
      address_text         → area_text
      ai_confidence        → confidence
      ai_authority_id      → recommended_authority (re-looked-up from JSON)
      image_original_path  → photo_filename
      image_redacted_path  → (stored; signed URL added by _attach_signed_urls)
      image_hash           → image_hash
      ai_raw_response      → description + match_reason + AI fields (JSONB)
      created_at           → created_at
      status               → status TEXT column (migration 007; default 'SUBMITTED')
      rejection_reason     → rejection_reason TEXT column (migration 007; NULL unless REJECTED)
    """
    try:
        category_val = row.get("ai_category") or "other"
        raw = row.get("ai_raw_response") or {}
        description = raw.get("description", "")
        match_reason = raw.get("match_reason")
        confidence = float(row.get("ai_confidence") or 0.0)
        authority_id = row.get("ai_authority_id")
        authority_dict = get_authority_by_id(authority_id) if authority_id else None
        created_at_val = row.get("created_at")
        if isinstance(created_at_val, str):
            from datetime import datetime as _dt
            # Supabase returns ISO strings; parse robustly.
            created_at_val = _dt.fromisoformat(
                created_at_val.replace("Z", "+00:00")
            )

        # Read status from DB row (migration 007).  Fall back to SUBMITTED for
        # rows that pre-date the migration (status column absent or None).
        raw_status = row.get("status") or "SUBMITTED"
        try:
            db_status = ReportStatus(raw_status)
        except ValueError:
            db_status = ReportStatus.submitted

        return ReportOut(
            report_id=str(row["id"]),
            category=IssueCategory(category_val),
            category_label=CATEGORY_LABELS.get(category_val, category_val),
            area_text=row.get("address_text") or "",
            description=description,
            status=db_status,
            recommended_authority=_authority_dict_to_out(authority_dict),
            match_reason=match_reason,
            confidence=min(max(confidence, 0.0), 1.0),
            created_at=created_at_val or datetime.now(timezone.utc),
            photo_filename=row.get("image_original_path"),
            # T3-3: AI pipeline fields stored in ai_raw_response JSONB
            is_duplicate=bool(raw.get("is_duplicate", False)),
            duplicate_report_id=raw.get("duplicate_report_id"),
            image_hash=row.get("image_hash"),
            llm_provider_used=raw.get("llm_provider_used"),
            yolo_class=raw.get("yolo_class"),
            # Signed URLs are NOT stored in DB; they are generated on read.
            # _attach_signed_urls() adds them after row→ReportOut conversion.
            image_original_url=None,
            image_redacted_url=None,
            # Rejection reason from migration 007 column
            rejection_reason=row.get("rejection_reason"),
        )
    except Exception:
        logger.warning("_row_to_report_out: failed to parse DB row.", exc_info=True)
        return None


def _attach_signed_urls(report: ReportOut, original_path: Optional[str], redacted_path: Optional[str]) -> ReportOut:
    """Generate and attach 15-minute signed URLs to a ReportOut (T3-3 §20).

    Uses storage_service to create signed URLs.  If Supabase is unavailable
    or the path is None, the URL fields remain None — callers must handle this.

    Returns the same ReportOut object (mutated in place for simplicity).
    """
    if not _supabase_enabled():
        return report

    try:
        from services import storage_service

        if original_path:
            report.image_original_url = storage_service.get_original_signed_url(original_path)
        if redacted_path:
            report.image_redacted_url = storage_service.get_redacted_signed_url(redacted_path)
    except Exception:
        logger.warning("_attach_signed_urls: failed to generate signed URLs.", exc_info=True)

    return report


